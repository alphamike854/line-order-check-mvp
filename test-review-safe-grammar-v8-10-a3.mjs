import assert from "node:assert/strict";
import { parseOrder, PARSER_VERSION } from "./src/lib/order-parser.mjs";

function byKey(result) {
  return Object.fromEntries(
    result.items.map((item) => [
      `${item.category}${item.code}`,
      item.quantity,
    ])
  );
}

assert.equal(PARSER_VERSION, "1.6.1");

// ------------------------------------------------------------
// Pending 2-digit codes + composite modifier quantity.
// Review corpus:
// 80
// 18
// บลก 15
//
// บลก = A + B + reverse.
// ------------------------------------------------------------
{
  const result = parseOrder(`80
18
บลก 15`);

  assert.equal(result.status, "PARSED");

  assert.deepEqual(byKey(result), {
    A08: 15,
    A18: 15,
    A80: 15,
    A81: 15,

    B08: 15,
    B18: 15,
    B80: 15,
    B81: 15,
  });
}

// ------------------------------------------------------------
// Repeated hyphen is still a CODE LIST separator.
// It must never mean assignment by itself.
// ------------------------------------------------------------
{
  const result = parseOrder(`82--89--81
29--21--91
บลก 10`);

  assert.equal(result.status, "PARSED");

  const items = byKey(result);

  // Source codes.
  for (const code of [
    "82", "89", "81",
    "29", "21", "91",
  ]) {
    assert.equal(items[`A${code}`], 10);
    assert.equal(items[`B${code}`], 10);
  }

  // Reverse codes generated by บลก.
  for (const code of [
    "28", "98", "18",
    "92", "12", "19",
  ]) {
    assert.equal(items[`A${code}`], 10);
    assert.equal(items[`B${code}`], 10);
  }

  assert.equal(result.items.length, 24);
}

// ------------------------------------------------------------
// High-confidence 3-digit natural space assignment.
// Only short SINGLE quantity is included in A3.
// ------------------------------------------------------------
{
  const result = parseOrder(`220 10
202 10
022 10`);

  assert.equal(result.status, "PARSED");

  assert.deepEqual(byKey(result), {
    E022: 10,
    E202: 10,
    E220: 10,
  });
}

// ------------------------------------------------------------
// High-confidence 3-digit E/F pair.
//
// q2 > 6 deliberately keeps this outside historical
// "quantity x permutation-count" ambiguity.
// ------------------------------------------------------------
{
  const result = parseOrder("086 20*20");

  assert.equal(result.status, "PARSED");

  assert.deepEqual(byKey(result), {
    E086: 20,
    F086: 20,
  });
}

// ------------------------------------------------------------
// 2-digit CODE + pair quantity separated by whitespace.
// ------------------------------------------------------------
{
  const result = parseOrder("86 20*20");

  assert.equal(result.status, "PARSED");

  assert.deepEqual(byKey(result), {
    A86: 20,
    B86: 20,
  });
}

// ------------------------------------------------------------
// Compact star form found in Review:
// 77*20*20
// means code 77 = A20 / B20.
// ------------------------------------------------------------
{
  const result = parseOrder("77*20*20");

  assert.equal(result.status, "PARSED");

  assert.deepEqual(byKey(result), {
    A77: 20,
    B77: 20,
  });
}

// ============================================================
// SAFETY CASES
// ============================================================

// Two bare 2-digit values are codes, NOT code+quantity.
{
  const result = parseOrder("72 27");

  assert.notEqual(
    result.status,
    "PARSED",
    "72 27 must remain ambiguous"
  );

  assert.equal(
    result.items.length,
    0,
    "A3 must not interpret 27 as quantity"
  );
}

// Existing permutation ambiguity remains untouched.
//
// 249=5*5 currently has historical permutation semantics.
// A3 must not silently reinterpret the whitespace equivalent
// as E/F.
{
  const result = parseOrder("249 5*5");

  assert.ok(
    result.status === "REVIEW" ||
    result.status === "PARTIAL",
    "249 5*5 must stay Review-safe"
  );

  assert.equal(
    result.items.length,
    0,
    "A3 must not manufacture E/F items for 249 5*5"
  );
}

// Explicit historical counted permutation shorthand must not
// be rewritten by natural-space normalization.
{
  const result = parseOrder("123 20*6");

  assert.ok(
    result.status === "REVIEW" ||
    result.status === "PARTIAL",
    "123 20*6 remains outside A3 natural-space grammar"
  );
}

// 3-digit dash assignment is intentionally outside A3.
{
  const result = parseOrder("593-50*50");

  assert.ok(
    !result.items.some(
      (item) => item.code === "593"
    ),
    "A3 must not introduce 3-digit dash assignment"
  );
}

// Old critical ambiguity remains safe.
{
  const result = parseOrder(`69
96:300/300
10
01`);

  assert.equal(result.status, "PARTIAL");

  assert.deepEqual(byKey(result), {
    A69: 300,
    A96: 300,
    B69: 300,
    B96: 300,
  });

  assert.ok(
    result.errors.some(
      (error) =>
        error.code ===
        "PENDING_CODES_WITHOUT_QUANTITY"
    )
  );
}

console.log(
  "PASS: Review high-confidence natural assignment grammar v8.10 A3"
);
